def associations(group: pd.DataFrame, baseline: dict, top=4):
    """Subgroup shares vs the all-churner baseline. Returns actual numbers."""
    out = []
    for col in PROFILE_FIELDS:
        for val, share in group[col].value_counts(normalize=True).items():
            base = baseline[col].get(val, 0.0)
            if base > 0.02 and share > 0.15:
                out.append((abs(share - base), col, val, share, base))
    out.sort(reverse=True)
    return out[:top]


